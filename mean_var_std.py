def calculate(arr):

  arr = arr.reshape(3,3)

  mean_0 = arr.mean(axis=0)
  mean_1 = arr.mean(axis=1)
  mean_flat = arr.mean()

  var_0 = arr.var(axis=0)
  var_1 = arr.var(axis=1)
  var_flat = arr.var()

  std_0 = arr.std(axis=0)
  std_1 = arr.std(axis=1)
  std_flat = arr.std()

  max_0 = arr.max(axis=0)
  max_1 = arr.max(axis=1)
  max_flat = arr.max()

  min_0 = arr.min(axis=0)
  min_1 = arr.min(axis=1)
  min_flat = arr.min()

  sum_0 = arr.sum(axis=0)
  sum_1 = arr.sum(axis=1)
  sum_flat = arr.sum()

  sol_dic = {
      'mean': [mean_0.tolist(), mean_1.tolist(), mean_flat.tolist()],
      'variance': [var_0.tolist(), var_1.tolist(), var_flat.tolist()],
      'standard deviation': [std_0.tolist(), std_1.tolist(), std_flat.tolist()],
      'max': [max_0.tolist(), max_1.tolist(), max_flat.tolist()],
      'min': [min_0.tolist(), min_1.tolist(), min_flat.tolist()],
      'sum': [sum_0.tolist(), sum_1.tolist(), sum_flat.tolist()]
  }

  return sol_dic

def print_solution(sol):
  for key, value in sol.items():
    print(key, value)

